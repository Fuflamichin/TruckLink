$ErrorActionPreference = 'Stop'
Set-Location (Join-Path $PSScriptRoot '..')
if (-not (Get-Command flutter -ErrorAction SilentlyContinue)) {
  throw 'Flutter SDK not found. Install Flutter and add it to PATH.'
}
flutter config --enable-windows-desktop
# flutter create fills missing Windows/Android/iOS runner folders without overwriting our lib/pubspec.
flutter create --platforms=windows --project-name trucklink_desktop --org com.trucklink -t app --no-pub apps/desktop
flutter create --platforms=android,ios --project-name trucklink_mobile --org com.trucklink -t app --no-pub apps/mobile
# Remove the autogenerated counter-app tests (not relevant to the TruckLink UI).
Remove-Item apps/desktop/test/widget_test.dart -ErrorAction SilentlyContinue
Remove-Item apps/mobile/test/widget_test.dart -ErrorAction SilentlyContinue
# Temporary Android development-only HTTP/WebSocket allowance.
$manifest = 'apps/mobile/android/app/src/main/AndroidManifest.xml'
if (Test-Path $manifest) {
  $xml = Get-Content $manifest -Raw
  if ($xml -notmatch 'android.permission.INTERNET') {
    $xml = $xml.Replace('<application', '<uses-permission android:name="android.permission.INTERNET"/><application')
  }
  if ($xml -notmatch 'usesCleartextTraffic') {
    $xml = $xml.Replace('<application', '<application android:usesCleartextTraffic="true"')
  }
  Set-Content -Path $manifest -Value $xml -Encoding utf8
}
flutter pub get
Write-Host 'Done. Run: cd apps/desktop; flutter run -d windows'
