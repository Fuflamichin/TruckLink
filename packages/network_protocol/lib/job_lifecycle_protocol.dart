import 'dart:convert';

import 'package:telemetry_core/job_telemetry.dart';

import 'network_protocol.dart' show protocolVersion;

// ============================================
// JOB EVENTS
// ============================================

enum JobLifecycleEventKind { started, delivered, cancelled }

const String jobEventMessageType = 'job_event';

// ============================================
// EVENT WITH OPTIONAL HISTORY DATA
// ============================================

class JobLifecycleMessage {
  const JobLifecycleMessage({
    required this.event,
    this.eventId,
    this.occurredAtUtc,
    this.finalJob,
  });

  final JobLifecycleEventKind event;

  /// Unique identifier generated by Windows Hub.
  final String? eventId;

  /// Time when Hub observed the game event.
  final DateTime? occurredAtUtc;

  /// Last known job before its disappearance.
  final TruckLinkJobTelemetry? finalJob;
}

// ============================================
// ENCODE
// ============================================

String encodeJobEvent(
  JobLifecycleEventKind event, {
  String? eventId,
  DateTime? occurredAtUtc,
  TruckLinkJobTelemetry? finalJob,
}) {
  return jsonEncode({
    'version': protocolVersion,
    'type': jobEventMessageType,
    'event': event.name,

    // Optional additions for TruckLink v0.8.1.
    if (eventId != null) 'eventId': eventId,
    if (occurredAtUtc != null)
      'occurredAtUtc': occurredAtUtc.toUtc().toIso8601String(),
    if (finalJob != null) 'job': finalJob.toJson(),
  });
}

// ============================================
// RECOGNIZE
// ============================================

bool isJobEventMessage(String message) {
  try {
    final data = jsonDecode(message);

    return data is Map<String, dynamic> && data['type'] == jobEventMessageType;
  } on FormatException {
    return false;
  }
}

// ============================================
// DECODE COMPLETE EVENT
// ============================================

JobLifecycleMessage decodeJobEventDetails(String message) {
  final data = jsonDecode(message);

  if (data is! Map<String, dynamic>) {
    throw const FormatException('Invalid job event envelope');
  }

  if (data['version'] != protocolVersion ||
      data['type'] != jobEventMessageType) {
    throw const FormatException('Unsupported job event message');
  }

  final kind = switch (data['event']) {
    'started' => JobLifecycleEventKind.started,
    'delivered' => JobLifecycleEventKind.delivered,
    'cancelled' => JobLifecycleEventKind.cancelled,
    _ => throw const FormatException('Unknown job event'),
  };

  String? eventId;

  final rawId = data['eventId'];

  if (rawId != null) {
    if (rawId is! String || rawId.trim().isEmpty) {
      throw const FormatException('Invalid job event ID');
    }

    eventId = rawId;
  }

  DateTime? occurredAtUtc;

  final rawTime = data['occurredAtUtc'];

  if (rawTime != null) {
    if (rawTime is! String) {
      throw const FormatException('Invalid event time');
    }

    occurredAtUtc = DateTime.tryParse(rawTime)?.toUtc();

    if (occurredAtUtc == null) {
      throw const FormatException('Invalid event date');
    }
  }

  TruckLinkJobTelemetry? finalJob;

  final rawJob = data['job'];

  if (rawJob != null) {
    if (rawJob is! Map<String, dynamic>) {
      throw const FormatException('Invalid final job data');
    }

    finalJob = TruckLinkJobTelemetry.fromJson(rawJob);
  }

  return JobLifecycleMessage(
    event: kind,
    eventId: eventId,
    occurredAtUtc: occurredAtUtc,
    finalJob: finalJob,
  );
}

// ============================================
// BACKWARD-COMPATIBLE DECODE
// ============================================

JobLifecycleEventKind decodeJobEvent(String message) {
  return decodeJobEventDetails(message).event;
}
